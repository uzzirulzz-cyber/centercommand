export function presetById(id) {
  return PRESETS.find((p) => p.id === id) || null;
}

/** Full token set for a preset id (merged onto the defaults). */
export function presetTokens(id, customPresets = []) {
  const custom = (customPresets || []).find((p) => p.id === id);
  if (custom) {
    const merged = mergeTokens(DEFAULT_TOKENS, custom.tokens || {});
    // Carry the preset's own name/id so publishing reports the right theme.
    merged.meta = { ...merged.meta, name: custom.name || merged.meta?.name, presetId: custom.id };
    return merged;
  }
  const preset = presetById(id);
  if (!preset) return JSON.parse(JSON.stringify(DEFAULT_TOKENS));
  const merged = mergeTokens(DEFAULT_TOKENS, preset.tokens);
  merged.meta = { ...merged.meta, name: preset.name, presetId: preset.id };
  return merged;
}

